  static ReminderCopy morningForDate(DateTime date, AppLocalizations l10n) =>
      pick(pool: morning(l10n), date: date, salt: morningSalt);

  static ReminderCopy eveningForDate(DateTime date, AppLocalizations l10n) =>
      pick(pool: evening(l10n), date: date, salt: eveningSalt);

  static ReminderCopy pick({
    required List<ReminderCopy> pool,
    required DateTime date,
    required int salt,
  }) {
    final day = DateTime(date.year, date.month, date.day);
    final dayNumber = day.difference(DateTime.utc(2000, 1, 1)).inDays;
    final index =
        (dayNumber * 17 + salt.abs() % pool.length).abs() % pool.length;
    return pool[index];
  }
